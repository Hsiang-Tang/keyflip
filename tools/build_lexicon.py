#!/usr/bin/env python3
"""Build data/lexicon.tsv from pinned McBopomofo sources.

The English word list is built separately by tools/build_english.py.

Usage: python3 -I tools/build_lexicon.py [--src DIR] [--out DIR]
Stdlib only. Inputs are treated as untrusted data.
"""
import argparse
import datetime
import hashlib
import json
import os
import re
import sys
import tempfile
import urllib.request

MCB_REPO = "openvanilla/McBopomofo"
INPUTS = [
    # (file name, repo, path in repo)
    ("BPMFBase.txt", MCB_REPO, "Source/Data/BPMFBase.txt"),
    ("BPMFMappings.txt", MCB_REPO, "Source/Data/BPMFMappings.txt"),
    ("phrase.occ", MCB_REPO, "Source/Data/phrase.occ"),
    ("BPMFPunctuations.txt", MCB_REPO, "Source/Data/BPMFPunctuations.txt"),
]

READING_RE = re.compile(r"^(?:[ㄅ-ㄩ]+[ˊˇˋ˙]?|˙[ㄅ-ㄩ]+[ˊˇˋ]?)$")
BOPOMOFO_RE = re.compile(r"^[ㄅ-ㄩ]$")


def read_text(path):
    with open(path, "rb") as f:
        return f.read().decode("utf-8", errors="replace")


def parse_occ(text):
    """phrase.occ -> {phrase: count}; malformed lines are skipped."""
    occ = {}
    for line in text.splitlines():
        parts = line.split()
        if len(parts) != 2 or not parts[1].isascii() or not parts[1].isdigit():
            continue
        n = int(parts[1])
        if n > occ.get(parts[0], -1):
            occ[parts[0]] = n
    return occ


def parse_base(text, stats):
    """BPMFBase.txt -> list of (char, reading, common). Symbol entries are skipped.

    `common` is True unless the line's class column says `utf8`: upstream marks
    characters in the Big5 set `big5` and rare, simplified, or extension
    characters `utf8`. A line without the column counts as common."""
    out = []
    for line in text.splitlines():
        parts = line.split()
        if not parts:
            continue
        if len(parts) < 2 or len(parts[0]) != 1:
            stats["base_malformed"] += 1
            continue
        if BOPOMOFO_RE.match(parts[0]) or parts[0] in "ˊˇˋ˙":
            stats["base_symbol_skipped"] += 1
            continue
        if not READING_RE.match(parts[1]):
            stats["base_bad_reading"] += 1
            continue
        out.append((parts[0], parts[1], parts[-1] != "utf8"))
    return out


def parse_mappings(text, stats):
    """BPMFMappings.txt -> list of (phrase, [readings])."""
    out = []
    for line in text.splitlines():
        parts = line.split()
        if not parts:
            continue
        if len(parts) < 2:
            stats["map_malformed"] += 1
            continue
        phrase, readings = parts[0], parts[1:]
        if len(readings) != len(phrase):
            stats["map_length_mismatch"] += 1
            continue
        if not all(READING_RE.match(r) for r in readings):
            stats["map_bad_reading"] += 1
            continue
        out.append((phrase, readings))
    return out


def new_stats():
    return {k: 0 for k in ("base_malformed", "base_symbol_skipped", "base_bad_reading",
                           "map_malformed", "map_length_mismatch", "map_bad_reading")}


def build_tables(src):
    stats = new_stats()
    occ = parse_occ(read_text(os.path.join(src, "phrase.occ")))
    entries = {}
    # Value: (count, rare). rare is 1 for a non-Big5 character, else 0.
    for ch, rd, common in parse_base(read_text(os.path.join(src, "BPMFBase.txt")), stats):
        rare = 0 if common else 1
        if (rd, ch) in entries:
            rare = min(rare, entries[(rd, ch)][1])
        entries[(rd, ch)] = (occ.get(ch, 0), rare)
    for phrase, rds in parse_mappings(read_text(os.path.join(src, "BPMFMappings.txt")), stats):
        entries[(" ".join(rds), phrase)] = (occ.get(phrase, 0), 0)
    lex = "".join("%s\t%s\t%d\t%d\n" % (rd, tx, n, r)
                  for (rd, tx), (n, r) in sorted(entries.items()))
    return lex, stats


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        h.update(f.read())
    return h.hexdigest()


def write_bytes(path, text):
    with open(path, "wb") as f:
        f.write(text.encode("utf-8"))


def build(src, out, shas, date):
    lex, stats = build_tables(src)
    os.makedirs(out, exist_ok=True)
    write_bytes(os.path.join(out, "lexicon.tsv"), lex)
    lines = ["# Upstream sources for data/lexicon.tsv",
             "# Generated by tools/build_lexicon.py",
             "build_date: " + date,
             "repo: %s commit: %s" % (MCB_REPO, shas.get(MCB_REPO, "unknown"))]
    for name, repo, path in INPUTS:
        lines.append("file: %s repo: %s path: %s sha256: %s"
                     % (name, repo, path, sha256_file(os.path.join(src, name))))
    write_bytes(os.path.join(out, "SOURCES.txt"), "\n".join(lines) + "\n")
    return stats, lex.count("\n")


def http_get(url):
    req = urllib.request.Request(url, headers={"User-Agent": "keyflip-build-lexicon"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read()


def head_sha(repo):
    data = json.loads(http_get("https://api.github.com/repos/%s/commits/master" % repo))
    sha = data["sha"]
    if not re.fullmatch(r"[0-9a-f]{40}", sha):
        raise ValueError("bad sha for " + repo)
    return sha


def download(shas, dest):
    for name, repo, path in INPUTS:
        url = "https://raw.githubusercontent.com/%s/%s/%s" % (repo, shas[repo], path)
        with open(os.path.join(dest, name), "wb") as f:
            f.write(http_get(url))


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--src", help="directory holding the input files (else download)")
    default_out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "data")
    ap.add_argument("--out", default=default_out)
    ap.add_argument("--sha-mcbopomofo")
    a = ap.parse_args(argv)
    shas = {MCB_REPO: a.sha_mcbopomofo}
    for repo in list(shas):
        if not shas[repo]:
            try:
                shas[repo] = head_sha(repo)
            except Exception as e:  # network or API failure
                if not a.src:
                    sys.exit("cannot resolve %s commit: %s" % (repo, e))
                print("warning: cannot resolve %s commit (%s); recording unknown" % (repo, e),
                      file=sys.stderr)
                shas[repo] = "unknown"
    tmp = None
    src = a.src
    if not src:
        tmp = tempfile.TemporaryDirectory()
        src = tmp.name
        download(shas, src)
    epoch = os.environ.get("SOURCE_DATE_EPOCH")
    now = (datetime.datetime.fromtimestamp(int(epoch), datetime.timezone.utc)
           if epoch else datetime.datetime.now(datetime.timezone.utc))
    stats, nlex = build(src, a.out, shas, now.strftime("%Y-%m-%d"))
    print("lexicon.tsv: %d lines" % nlex, file=sys.stderr)
    for k, v in sorted(stats.items()):
        print("dropped/skipped %s: %d" % (k, v), file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
