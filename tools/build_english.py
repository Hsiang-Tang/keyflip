#!/usr/bin/env python3
"""Build data/english.txt (ranked English word list) from the wordfreq package.

Usage: python3 -I tools/build_english.py [--out DIR] [--count N]
Needs: pip install wordfreq==3.1.1 (code: Apache-2.0, data: CC BY-SA 4.0).
The list is the N most frequent lowercase a-z words, most frequent first.
Order matters: the engine uses rank (top 3,000 counts as "common English").
"""
import argparse
import os
import re
import sys

WORDFREQ_VERSION = "3.1.1"
WORD_RE = re.compile(r"^[a-z]+$")
# Single letters other than these are noise in web/subtitle corpora.
ONE_LETTER = {"a", "i"}
# Tokens that are corpus artifacts rather than words worth protecting, plus a short
# profanity blocklist so the shipped list stays clean.
BLOCKLIST = set("""
www http https com org net html php amp nbsp gt lt rt pm am
fuck fucking fucked fucker shit shitty bitch bitches asshole dick cock pussy cunt
bastard slut whore nigga nigger fag faggot porn sex sexy
""".split())


def build(words, count):
    seen, out = set(), []
    for w in words:
        w = w.strip().lower()
        if not WORD_RE.match(w) or w in seen or w in BLOCKLIST:
            continue
        if len(w) == 1 and w not in ONE_LETTER:
            continue
        seen.add(w)
        out.append(w)
        if len(out) == count:
            break
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    default_out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "data")
    ap.add_argument("--out", default=default_out)
    ap.add_argument("--count", type=int, default=10000)
    a = ap.parse_args(argv)
    try:
        import wordfreq
        from importlib.metadata import version
    except ImportError:
        sys.exit("wordfreq is required: pip install wordfreq==%s" % WORDFREQ_VERSION)
    ver = version("wordfreq")
    words = build(wordfreq.top_n_list("en", a.count * 2), a.count)
    os.makedirs(a.out, exist_ok=True)
    with open(os.path.join(a.out, "english.txt"), "wb") as f:
        f.write("".join(w + "\n" for w in words).encode("utf-8"))
    with open(os.path.join(a.out, "ENGLISH_SOURCE.txt"), "wb") as f:
        f.write(("# Source of data/english.txt (generated by tools/build_english.py)\n"
                 "package: wordfreq version: %s\n"
                 "license: data CC BY-SA 4.0 (https://github.com/rspeer/wordfreq), code Apache-2.0\n"
                 "words: %d\n" % (ver, len(words))).encode("utf-8"))
    print("english.txt: %d words (wordfreq %s)" % (len(words), ver), file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
